#!/usr/bin/env python3
"""Write src/libpng.cppm and src/options.cppm from png.h.

src/libpng.cppm exports every type, struct tag and function png.h declares
in this configuration by `export using` (the upstream globals, unchanged).
src/options.cppm is the partition of the macros module that holds
pnglibconf.h's options: each PNG_<NAME>_SUPPORTED as an `inline constexpr
bool`, true exactly when the macro is defined where the module is built.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, surface  # noqa: E402

# Option-like macros that are not pnglibconf.h's own: png.h's pre-1.5.4 name
# of READ_STRIP_16_TO_8 and pngconf.h's choice of the read macros.
EXTRA_OPTIONS = ['PNG_READ_16_TO_8_SUPPORTED', 'PNG_USE_READ_MACROS']

HEADER = '''// Generated by tools/gen_exports.py from png.h (libpng 1.6.43) — do not
// edit by hand.
//
// mcpplibs.mwrap.libpng — libpng, the PNG reference library, as a C++ module.
// Every exported name is the upstream global of <png.h>, unchanged; the root
// also re-exports the macro mappings. The library is compat.libpng (over
// compat.zlib), built from the same release.
module;
#include <png.h>

export module mcpplibs.mwrap.libpng;

export import mcpplibs.mwrap.libpng.macros;
'''

OPTIONS_HEADER = '''// Generated by tools/gen_exports.py from pnglibconf.h (libpng 1.6.43) — do
// not edit by hand.
//
// The options of the build, PNG_<NAME>_SUPPORTED, as `inline constexpr bool`
// in mcpplibs::mwrap::libpng::macros: each is true exactly when its macro is
// defined by the pnglibconf.h this module is built with (compat.libpng's).
// A partition of mcpplibs.mwrap.libpng.macros, which re-exports it.
module;
#include <png.h>

namespace mwrap_libpng_options {
'''


def render(sf):
    out = [HEADER]
    out.append(f'// types ({len(sf.types)})')
    out += [f'export using ::{n};' for n in sf.types]
    out.append(f'\n// struct tags ({len(sf.tags)})')
    out += [f'export using ::{n};' for n in sf.tags]
    out.append(f'\n// functions ({len(sf.functions)}; deprecated upstream: {", ".join(sf.deprecated)})')
    out += [f'export using ::{n};' for n in sf.functions]
    cppm = '\n'.join(out) + '\n'

    options = sf.options + EXTRA_OPTIONS
    opt = [OPTIONS_HEADER]
    for name in options:
        opt += [f'#ifdef {name}', f'inline constexpr bool value_{name} = true;', '#else',
                f'inline constexpr bool value_{name} = false;', '#endif']
    opt.append('}  // namespace mwrap_libpng_options\n')
    opt += [f'#undef {name}' for name in options]
    opt += ['', 'export module mcpplibs.mwrap.libpng.macros:options;', '',
            'export namespace mcpplibs::mwrap::libpng::macros {', '']
    opt += [f'inline constexpr bool {name} = mwrap_libpng_options::value_{name};' for name in options]
    opt.append('\n}  // namespace mcpplibs::mwrap::libpng::macros\n')
    return cppm, '\n'.join(opt)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    cppm, options = render(surface(fetch(root)))
    stale = []
    for path, text in ((root / 'src/libpng.cppm', cppm), (root / 'src/options.cppm', options)):
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
